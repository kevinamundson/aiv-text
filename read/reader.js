/* AIV reader: book panel (search, OT/NT list, chapter grid) and keyboard chapter navigation.
   Hand-written; book data comes from nav-data.js (generated by tools/build_reader.py).
   Without JavaScript the title links to the book's chapter list and the round buttons are plain links. */
(function () {
  "use strict";
  var BOOKS = window.AIV_BOOKS || [];
  var body = document.body, page = document.querySelector(".page");
  var curBook = body.dataset.book || "", curCh = body.dataset.chapter || "";
  var ALIAS = {jn:"JHN",joh:"JHN",mk:"MRK",mr:"MRK",mt:"MAT",lk:"LUK",lu:"LUK",ac:"ACT",
    ro:"ROM",rm:"ROM",ga:"GAL",ep:"EPH",phil:"PHP",php:"PHP",phm:"PHM",philem:"PHM",col:"COL",
    he:"HEB",jas:"JAS",jm:"JAS",jud:"JUD",jude:"JUD",re:"REV",rv:"REV",revelations:"REV",
    ge:"GEN",gn:"GEN",ex:"EXO",lv:"LEV",le:"LEV",nu:"NUM",nm:"NUM",dt:"DEU",de:"DEU",
    jsh:"JOS",jos:"JOS",jg:"JDG",jdg:"JDG",judg:"JDG",ru:"RUT",ps:"PSA",psa:"PSA",psalm:"PSA",
    pss:"PSA",pr:"PRO",prv:"PRO",ec:"ECC",eccl:"ECC",qoh:"ECC",so:"SNG",sos:"SNG",song:"SNG",
    canticles:"SNG",is:"ISA",je:"JER",la:"LAM",eze:"EZK",ezek:"EZK",ezk:"EZK",da:"DAN",dn:"DAN",
    ho:"HOS",jl:"JOL",joel:"JOL",am:"AMO",ob:"OBA",jon:"JON",mi:"MIC",na:"NAM",nah:"NAM",
    hab:"HAB",zep:"ZEP",zeph:"ZEP",hag:"HAG",zec:"ZEC",zech:"ZEC",mal:"MAL",ezr:"EZR",ne:"NEH",
    es:"EST",est:"EST",jb:"JOB"};
  var norm = function (s) { return s.toLowerCase().replace(/[\s.’'\-]+/g, "").replace(/^(i{1,3})(?=[a-z])/, function (m) { return String(m.length); }); };
  var byId = {}; BOOKS.forEach(function (b) { byId[b[0]] = b; });
  var href = function (id, ch) { return "/read/" + id + "/" + ch; };
  var el = function (tag, cls, text) { var e = document.createElement(tag); if (cls) e.className = cls; if (text != null) e.textContent = text; return e; };

  function parse(q) {
    var m = q.trim().match(/^(.*?[a-z’'.])\s*(\d+)?(?:\s*[:.]\s*(\d+))?\s*$/i);
    if (!m) return null;
    var key = norm(m[1]); if (!key) return null;
    var hits = BOOKS.filter(function (b) {
      return norm(b[1]).indexOf(key) === 0 || b[0].toLowerCase().indexOf(key) === 0;
    });
    if (ALIAS[key] && hits.indexOf(byId[ALIAS[key]]) < 0) hits.unshift(byId[ALIAS[key]]);
    else if (ALIAS[key]) { hits.splice(hits.indexOf(byId[ALIAS[key]]), 1); hits.unshift(byId[ALIAS[key]]); }
    var exact = BOOKS.filter(function (b) { return norm(b[1]) === key || b[0].toLowerCase() === key; });
    if (exact.length) { hits.splice(hits.indexOf(exact[0]), 1); hits.unshift(exact[0]); }
    return {hits: hits, ch: m[2] ? parseInt(m[2], 10) : null, v: m[3] ? parseInt(m[3], 10) : null};
  }

  /* ---- build the panel ---- */
  var scrim = el("div", "scrim"); scrim.hidden = true;
  var panel = el("aside", "panel"); panel.id = "panel"; panel.hidden = true;
  panel.setAttribute("role", "dialog"); panel.setAttribute("aria-modal", "true");
  panel.setAttribute("aria-label", "Books of the Bible");
  var head = el("div", "panel-head");
  var brand = el("a", "panel-brand"); brand.href = "/";
  brand.appendChild(el("span", "brand-name", "Amundson Interpretive Version"));
  brand.appendChild(el("span", "status", "DRAFT"));
  var close = el("button", "panel-close"); close.type = "button"; close.setAttribute("aria-label", "Close"); close.textContent = "×";
  head.appendChild(brand); head.appendChild(close);
  var form = el("form", "panel-search"); form.setAttribute("role", "search");
  var input = el("input"); input.type = "search"; input.placeholder = "Book or chapter, e.g. jn 3, Psalm 23";
  input.setAttribute("aria-label", "Find a book or chapter"); input.autocomplete = "off"; input.spellcheck = false;
  var go = el("a", "panel-go"); go.hidden = true;
  form.appendChild(input); form.appendChild(go);
  /* Book list: rows of [Old Testament, New Testament] that meet at the centre line.
     Tapping a book opens its chapter grid right under that row (one open at a time). */
  var listView = el("div", "panel-books");
  listView.appendChild(el("h2", "panel-h", "Books of the Bible"));
  var rowsEl = el("div", "panel-rows");
  var empty = el("p", "panel-empty", "No book matches."); empty.hidden = true;
  var OT = BOOKS.filter(function (b) { return b[3] === "OT"; }), NT = BOOKS.filter(function (b) { return b[3] === "NT"; });
  var rows = [], cells = {};
  for (var r = 0; r < Math.max(OT.length, NT.length); r++) {
    var row = el("div", "panel-row"), pair = [];
    [[OT[r], "ot"], [NT[r], "nt"]].forEach(function (x) {
      var c = el("div", "panel-cell " + x[1]);
      if (x[0]) {
        var a = el("a", "", x[0][1]); a.href = href(x[0][0], 1); a.dataset.book = x[0][0];
        a.setAttribute("aria-expanded", "false");
        if (x[0][0] === curBook) a.setAttribute("aria-current", "true");
        c.appendChild(a); cells[x[0][0]] = {cell: c, a: a, row: row};
      }
      row.appendChild(c); pair.push(x[0] ? [c, x[0]] : null);
    });
    rowsEl.appendChild(row); rows.push([row, pair]);
  }
  listView.appendChild(rowsEl); listView.appendChild(empty);
  var foot = el("p", "panel-foot");
  foot.innerHTML = '<a class="raw" href="/#books">Raw USX files</a> · <a href="/">Home</a>';
  panel.appendChild(head); panel.appendChild(form); panel.appendChild(listView); panel.appendChild(foot);
  body.appendChild(scrim); body.appendChild(panel);

  var openId = null, pop = null;
  function closeGrid() {
    if (pop) pop.remove();
    if (openId && cells[openId]) { cells[openId].a.setAttribute("aria-expanded", "false"); cells[openId].cell.classList.remove("open"); }
    pop = null; openId = null;
  }
  function showGrid(id, focus) {
    var b = byId[id]; if (!b) return;
    closeGrid();
    var c = cells[id];
    pop = el("div", "panel-pop " + (b[3] === "OT" ? "from-ot" : "from-nt")); pop.id = "chapters-" + id;
    var ul = el("ul", "panel-grid" + (b[2] < 5 ? " few" : "")); ul.setAttribute("aria-label", "Chapters of " + b[1]);
    for (var i = 1; i <= b[2]; i++) {
      var li = el("li"), a = el("a", "", String(i)); a.href = href(b[0], i);
      a.setAttribute("aria-label", (b[0] === "PSA" ? "Psalm " : b[1] + " ") + i);
      if (b[0] === curBook && String(i) === curCh) a.setAttribute("aria-current", "page");
      li.appendChild(a); ul.appendChild(li);
    }
    pop.appendChild(ul);
    c.row.after(pop);
    c.a.setAttribute("aria-expanded", "true"); c.a.setAttribute("aria-controls", pop.id); c.cell.classList.add("open");
    openId = id;
    if (focus) (ul.querySelector('[aria-current="page"]') || ul.querySelector("a")).focus();
    var cur = ul.querySelector('[aria-current="page"]');
    (cur || c.a).scrollIntoView({block: "nearest"});
  }
  rowsEl.addEventListener("click", function (e) {
    var a = e.target.closest("a[data-book]"); if (!a) return;
    e.preventDefault();
    if (openId === a.dataset.book) closeGrid(); else showGrid(a.dataset.book, false);
  });

  function filter() {
    var q = input.value, p = q.trim() ? parse(q) : null, n = 0;
    closeGrid();
    rows.forEach(function (r) {
      var any = false;
      r[1].forEach(function (it) {
        if (!it) return;
        var show = !q.trim() || (p && p.hits.indexOf(it[1]) >= 0);
        it[0].classList.toggle("off", !show); if (show) { any = true; n++; }
      });
      r[0].hidden = !any;
    });
    empty.hidden = n > 0;
    if (p && p.hits.length) {
      var b = p.hits[0], ch = Math.min(Math.max(p.ch || 1, 1), b[2]);
      go.href = href(b[0], ch) + (p.v && p.ch ? "#v" + p.v : "");
      go.textContent = "Go to " + (b[0] === "PSA" ? "Psalm" : b[1]) + " " + ch + (p.v && p.ch ? ":" + p.v : "") + " ›";
      go.hidden = false;
    } else go.hidden = true;
  }
  input.addEventListener("input", filter);
  form.addEventListener("submit", function (e) { e.preventDefault(); if (!go.hidden) location.href = go.href; });

  /* ---- open / close ---- */
  var openers = document.querySelectorAll("[data-open]"), lastFocus = null;
  function setOpen(open, focusSearch) {
    panel.hidden = scrim.hidden = !open;
    body.classList.toggle("panel-open", open);
    openers.forEach(function (o) { o.setAttribute("aria-expanded", String(open)); });
    document.querySelectorAll(".page, .fab").forEach(function (n) { if (open) n.setAttribute("inert", ""); else n.removeAttribute("inert"); });
    if (open) {
      if (curBook && byId[curBook] && openId !== curBook && !input.value.trim()) showGrid(curBook, false);
      if (focusSearch || !curBook) input.focus();
      else (pop && pop.querySelector('[aria-current="page"]') || close).focus();
    } else if (lastFocus) lastFocus.focus();
  }
  openers.forEach(function (o) {
    o.addEventListener("click", function (e) { e.preventDefault(); lastFocus = o; setOpen(true, o.dataset.open === "search"); });
  });
  close.addEventListener("click", function () { setOpen(false); });
  scrim.addEventListener("click", function () { setOpen(false); });
  document.addEventListener("keydown", function (e) {
    if (e.key === "Escape" && !panel.hidden) { e.preventDefault(); setOpen(false); return; }
    if (!panel.hidden || e.altKey || e.ctrlKey || e.metaKey || e.shiftKey) return;
    var t = e.target; if (t && (t.isContentEditable || /^(INPUT|TEXTAREA|SELECT)$/.test(t.tagName))) return;
    var a = e.key === "ArrowLeft" ? document.querySelector(".fab.prev") : e.key === "ArrowRight" ? document.querySelector(".fab.next") : null;
    if (a) { e.preventDefault(); location.href = a.href; }
  });
  /* keep keyboard focus inside the open panel */
  panel.addEventListener("keydown", function (e) {
    if (e.key !== "Tab") return;
    var f = Array.prototype.filter.call(panel.querySelectorAll("a[href],button,input"), function (x) { return x.offsetParent !== null; });
    if (!f.length) return;
    if (e.shiftKey && document.activeElement === f[0]) { e.preventDefault(); f[f.length - 1].focus(); }
    else if (!e.shiftKey && document.activeElement === f[f.length - 1]) { e.preventDefault(); f[0].focus(); }
  });
})();
